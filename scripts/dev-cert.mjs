#!/usr/bin/env node
// Generate a self-signed TLS certificate for local development.
//
// WHY THIS EXISTS
// ---------------
// Every endpoint in this system is https, loopback included, so the server
// will not start without TLS material. `.env.example` ships
//
//     TLS_CERT_PATH=/srv/office/tls/dev-cert.pem
//
// which is a *production* path that exists on no developer's machine. Copy
// `.env.example` to `.env` verbatim, run the tests, and roughly a dozen
// suites fail with ENOENT errors that look like broken code rather than a
// missing file. That trap was unowned by any ticket and cost time more than
// once; this closes it.
//
// On a real host the same pair is generated by
// deploy/host/provision-host.sh, which needs root. This script is the
// developer-machine equivalent and needs nothing.
//
//   node scripts/dev-cert.mjs            # writes .devtls/{cert,key}.pem
//   node scripts/dev-cert.mjs --force    # overwrite an existing pair
//
// Node cannot mint an X.509 certificate on its own — `crypto.X509Certificate`
// parses, it does not issue — so this shells out to openssl. openssl is
// present on any Linux host and ships inside Git for Windows, which is why
// the search below looks there: it is NOT on the Windows PATH by default,
// and "openssl: command not found" on a machine that has openssl is exactly
// the kind of dead end this script exists to prevent.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(repoRoot, ".devtls");
const certPath = path.join(outDir, "cert.pem");
const keyPath = path.join(outDir, "key.pem");
const force = process.argv.includes("--force");

const OPENSSL_CANDIDATES = [
  "openssl",
  // Git for Windows bundles openssl but does not put it on PATH.
  "C:/Program Files/Git/usr/bin/openssl.exe",
  "C:/Program Files/Git/mingw64/bin/openssl.exe",
  "C:/Program Files (x86)/Git/usr/bin/openssl.exe",
];

function findOpenssl() {
  for (const candidate of OPENSSL_CANDIDATES) {
    try {
      execFileSync(candidate, ["version"], { stdio: "ignore" });
      return candidate;
    } catch {
      // Not this one; try the next.
    }
  }
  return null;
}

function fail(message) {
  console.error(`dev-cert: ${message}`);
  process.exit(1);
}

if (existsSync(certPath) && existsSync(keyPath) && !force) {
  console.log(`dev-cert: ${path.relative(repoRoot, certPath)} already exists (use --force to replace)`);
  printEnv();
  process.exit(0);
}

const openssl = findOpenssl();
if (!openssl) {
  fail(
    "no openssl found. Looked on PATH and in the Git for Windows install.\n" +
      "  Linux/macOS: install openssl with your package manager.\n" +
      "  Windows:     install Git for Windows, which bundles it.",
  );
}

mkdirSync(outDir, { recursive: true });

try {
  execFileSync(
    openssl,
    [
      "req", "-x509",
      "-newkey", "rsa:2048",
      "-nodes",
      "-days", "365",
      "-keyout", keyPath,
      "-out", certPath,
      "-subj", "/CN=localhost",
      // Both forms: the server binds loopback, and clients reach it by name
      // and by address depending on which config they read.
      "-addext", "subjectAltName=DNS:localhost,IP:127.0.0.1",
    ],
    { stdio: ["ignore", "ignore", "pipe"] },
  );
} catch (error) {
  fail(`openssl failed: ${error.stderr?.toString().trim() ?? error.message}`);
}

// .gitignore already excludes *.pem, so the pair cannot be committed by
// accident — worth stating here because a dev cert in a repo is the kind of
// thing that gets copied into production by someone in a hurry.
console.log(`dev-cert: wrote ${path.relative(repoRoot, certPath)} and ${path.relative(repoRoot, keyPath)}`);
printEnv();

function printEnv() {
  // Absolute paths with forward slashes: dotenv does not expand `~` or
  // resolve relative paths, and a backslash in a .env value is an escape.
  const asEnv = (p) => p.replace(/\\/g, "/");
  console.log("\nPoint .env at them:\n");
  console.log(`  TLS_CERT_PATH=${asEnv(certPath)}`);
  console.log(`  TLS_KEY_PATH=${asEnv(keyPath)}`);
}
