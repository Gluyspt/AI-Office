#!/usr/bin/env node
// Throwaway hook echo server for spike 002 (ticket docs/tasks/002-spike-hook-payloads.md).
// Logs every hook POST verbatim to stdout and to an append-only JSONL file, and can be
// told at runtime to answer a given path with a chosen status/body so blocking-response
// shapes can be probed without restarting Claude Code.
//
// TLS ONLY. Decided: every hook endpoint in this system is https, including on loopback
// (see docs/tasks/README.md, "Decisions made"). The server generates a self-signed cert
// on first run if one is not already present.
//
//   node echo-server.mjs            # PORT=8787 LOG=$HOME/spike002-tmp/hook-events.jsonl
//
// ANSWERED on the 2026-09-22 re-run (Claude Code 2.1.278): the hook client does NOT
// accept a self-signed cert. Without a trusted CA every hook fails the handshake and no
// event arrives — the tlsClientError handler below logs `unknown ca`, which is the only
// way to tell that apart from "the hook never fired". The fix is to trust the CA, never
// to fall back to plaintext. This export is MANDATORY in the environment `claude` is
// launched with (the tmux/spawn env, not just a settings file):
//
//   export NODE_EXTRA_CA_CERTS=$SPIKE_TLS_DIR/cert.pem      # before launching claude
//
// See docs/spikes/001-hook-payloads.md §12.
//
// Control plane (not a hook path):
//   POST /control/mode   {"path":"/events/tool","status":200,"body":{...}}   -> set reply
//   POST /control/mode   {"path":"/events/tool","reset":true}               -> back to 200 {}
//   GET  /control/dump                                                      -> all events seen
//   GET  /control/clear                                                     -> forget them
//   GET  /health
//
// NOT production code: no auth, no persistence guarantees, unbounded memory.

import { createServer } from 'node:https';
import { appendFileSync, mkdirSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { execFileSync } from 'node:child_process';

const PORT = Number(process.env.PORT || 8787);
const LOG = process.env.LOG || `${process.env.HOME}/spike002-tmp/hook-events.jsonl`;
const DELAY_MS = Number(process.env.DELAY_MS || 0); // simulate a slow event server
const TLS_DIR = process.env.SPIKE_TLS_DIR || `${process.env.HOME}/spike002-tmp/tls`;

mkdirSync(dirname(LOG), { recursive: true });

// --- TLS material -----------------------------------------------------------
// Self-signed, loopback-only, regenerated by deleting the directory. The SAN
// covers both localhost and 127.0.0.1 because a hook URL may use either and a
// CN-only cert is rejected by every modern TLS client.
function ensureCert() {
  const key = join(TLS_DIR, 'key.pem');
  const cert = join(TLS_DIR, 'cert.pem');
  if (existsSync(key) && existsSync(cert)) return { key, cert };

  mkdirSync(TLS_DIR, { recursive: true });
  try {
    execFileSync('openssl', [
      'req', '-x509', '-newkey', 'rsa:2048',
      '-keyout', key, '-out', cert,
      '-days', '365', '-nodes',
      '-subj', '/CN=localhost',
      '-addext', 'subjectAltName=DNS:localhost,IP:127.0.0.1',
    ], { stdio: 'pipe' });
  } catch (err) {
    process.stderr.write(
      `could not generate a self-signed cert with openssl: ${err.message}\n` +
      `generate one by hand into ${TLS_DIR}, or set SPIKE_TLS_DIR to a directory holding key.pem and cert.pem\n`,
    );
    process.exit(1);
  }
  process.stdout.write(`generated a self-signed cert in ${TLS_DIR}\n`);
  return { key, cert };
}

const { key, cert } = ensureCert();

/** path -> { status, body, headers } */
const modes = new Map();
const seen = [];
let seq = 0;

function readBody(req) {
  return new Promise((resolve) => {
    const chunks = [];
    req.on('data', (c) => chunks.push(c));
    req.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
  });
}

function send(res, status, body, headers = {}) {
  const payload = typeof body === 'string' ? body : JSON.stringify(body);
  res.writeHead(status, { 'content-type': 'application/json', ...headers });
  res.end(payload);
}

const server = createServer(
  { key: readFileSync(key), cert: readFileSync(cert) },
  async (req, res) => {
    const tRecv = Date.now();
    const hrRecv = Number(process.hrtime.bigint() / 1000n) / 1000; // ms, monotonic
    const raw = await readBody(req);
    const url = new URL(req.url, `https://localhost:${PORT}`);

    if (url.pathname === '/health') return send(res, 200, { ok: true, seen: seen.length });

    if (url.pathname === '/control/dump') return send(res, 200, seen);
    if (url.pathname === '/control/clear') { seen.length = 0; return send(res, 200, { cleared: true }); }
    if (url.pathname === '/control/mode') {
      let cfg = {};
      try { cfg = JSON.parse(raw || '{}'); } catch { return send(res, 400, { error: 'bad json' }); }
      if (cfg.reset) modes.delete(cfg.path);
      else modes.set(cfg.path, { status: cfg.status ?? 200, body: cfg.body ?? {}, headers: cfg.headers ?? {} });
      return send(res, 200, { modes: [...modes.entries()] });
    }

    let parsed = null;
    try { parsed = JSON.parse(raw); } catch { /* keep raw */ }

    const record = {
      n: ++seq,
      t_recv_ms: tRecv,
      t_recv_iso: new Date(tRecv).toISOString(),
      hr_recv_ms: hrRecv,
      method: req.method,
      path: url.pathname,
      query: Object.fromEntries(url.searchParams),
      headers: req.headers,
      hook_event_name: parsed?.hook_event_name ?? null,
      session_id: parsed?.session_id ?? null,
      body_raw: raw,
      body: parsed,
    };
    seen.push(record);
    appendFileSync(LOG, JSON.stringify(record) + '\n');
    process.stdout.write(
      `[${record.t_recv_iso}] #${record.n} ${req.method} ${url.pathname} ` +
        `event=${record.hook_event_name} bytes=${raw.length}\n`,
    );

    const mode = modes.get(url.pathname);
    if (DELAY_MS) await new Promise((r) => setTimeout(r, DELAY_MS));
    if (mode) {
      process.stdout.write(`    -> replying ${mode.status} ${JSON.stringify(mode.body)}\n`);
      return send(res, mode.status, mode.body, mode.headers);
    }
    return send(res, 200, {});
  },
);

// TLS client errors surface here, not on the request handler. A hook client that
// refuses the self-signed cert shows up as a handshake failure and NO request —
// which would otherwise look identical to "the hook never fired".
server.on('tlsClientError', (err) => {
  process.stdout.write(`    !! TLS handshake rejected by client: ${err.message}\n`);
});

server.listen(PORT, '127.0.0.1', () => {
  process.stdout.write(`echo-server listening on https://127.0.0.1:${PORT} log=${LOG}\n`);
  process.stdout.write(`  cert: ${cert}  (export NODE_EXTRA_CA_CERTS=${cert} before launching claude)\n`);
});
